// JNI_OnLoad can see the application class loader, including on Android.
// Remember it before Zenoh's native threads need to construct callback values.
#[no_mangle]
pub extern "system" fn JNI_OnLoad(
    vm: jni::JavaVM,
    _reserved: *mut std::ffi::c_void,
) -> jni::sys::jint {
    let Ok(mut env) = vm.get_env() else {
        return jni::sys::JNI_ERR;
    };
    if let Err(err) =
        prebindgen_jni_runtime::init_class_loader(&mut env, "io/zenoh/jni/NativeLibrary")
    {
        eprintln!("Failed to initialize zenoh-flat-jni class loader: {err}");
        return jni::sys::JNI_ERR;
    }
    jni::sys::JNI_VERSION_1_6
}

